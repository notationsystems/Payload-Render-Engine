#!/usr/bin/env node
/**
 * THE SEVEN DOCUMENTS, GENERATED.
 *
 * The frontend charter names seven references and requires them read
 * before any route, data view or provenance interaction is designed.
 * They did not exist. Hand-writing them would have produced seven
 * documents restating shared/planes.mjs, shared/apis.mjs,
 * shared/platform.mjs and shared/ecosystem.mjs in prose - and prose
 * that restates a register drifts from it, usually within a day, and
 * then nobody can tell which is stale.
 *
 * This ecosystem already reached that conclusion and recorded it as a
 * convergence: doctrine that restates code is GENERATED from it, so it
 * cannot drift. So these are generated, and `npm run check` regenerates
 * and diffs - a document edited by hand fails the chain the way a
 * stale lockfile would.
 *
 * TWO KINDS OF CONTENT, marked in every file:
 *
 *   MEASURED  read from the registers at generation time. Counts,
 *             assignments, statuses, presence. Never typed by hand.
 *   AUTHORED  a decision or a rule, which no register can derive. It
 *             lives in this file, so there is still exactly one source.
 *
 * SCOPE. These describe THIS twin - the Payload Render Engine, a
 * read-only projection - and say so on every page. They are not a
 * description of a deployed Caravan, Tradewind or Landshark service,
 * and nothing here should be read as evidence that one exists.
 */

import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { registerRoutes } from '../server/api.mjs';
import { PLANES, MODULE_FAMILIES, ROUTE_PLANES, planeCoverage, planeOf, LIMB_INVARIANT, INVARIANT_ID, INVARIANT_EXTENSION } from '../shared/planes.mjs';
import { APIS, PRODUCT_HIERARCHY, STREAM_OWNERS, streamCoverage, ownerOf } from '../shared/apis.mjs';
