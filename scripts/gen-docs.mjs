// ---------------------------------------------------------------- emit
const CHECK = process.argv.includes('--check');
let drift = 0;
for (const [rel, content] of Object.entries(files)) {
  const path = join(ROOT, rel);
  mkdirSync(dirname(path), { recursive: true });
  const existing = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (CHECK) {
    if (existing !== content) {
      drift += 1;
      console.error(`  DRIFT ${rel}${existing === null ? ' (missing)' : ''}`);
    } else {
      console.log(`  ok   ${rel}`);
    }
  } else {
    writeFileSync(path, content);
    console.log(`  ${existing === content ? 'unchanged' : 'written  '} ${rel}`);
  }
}
if (CHECK && drift) {
  console.error(`\nDOC DRIFT - ${drift} of ${Object.keys(files).length} generated documents differ from the registers.`);
  console.error('REMEDY: run `node scripts/gen-docs.mjs` and commit the result. These files are generated so they cannot drift from the code they describe; editing one by hand is the drift this check exists to catch.');
  process.exit(1);
}
console.log(`\n${CHECK ? 'DOCS IN SYNC' : 'DOCS GENERATED'} - ${Object.keys(files).length} documents`);
